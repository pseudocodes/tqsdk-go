// Command gen 根据 model 包结构体的 `tq` 标签生成字段编号、有效位类型和名称表。
//
// 结构体本身就是 schema：带 `tq:"wire_name"` 标签的字段按声明顺序编号；
// 标签指向另一个结构体时展开为 "parent.child" 形式的叶字段。
// core 在运行时用反射按同样规则建立解码表，并在初始化时校验两者一致。
//
// 用法：在 model 目录执行 `go generate`。
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"reflect"
	"sort"
	"strconv"
	"strings"
)

// models 是需要生成字段编号的模型，顺序即输出顺序。
var models = []string{
	"Quote", "Instrument", "Kline", "Tick",
	"Account", "Position", "Order", "Trade", "Notify",
	"RemoteRiskRule", "RemoteRiskData",
}

type leaf struct {
	ident string // Go 常量后缀，如 AskPrice1 / SelfTradeCountLimit
	wire  string // 线上名称，如 ask_price1 / self_trade.count_limit
}

func main() {
	fset := token.NewFileSet()
	pkgs, err := parser.ParseDir(fset, ".", func(fi os.FileInfo) bool {
		n := fi.Name()
		return !strings.HasSuffix(n, "_test.go") && !strings.HasSuffix(n, "_gen.go")
	}, 0)
	if err != nil {
		fail(err)
	}
	structs := map[string]*ast.StructType{}
	for _, pkg := range pkgs {
		for _, f := range pkg.Files {
			ast.Inspect(f, func(n ast.Node) bool {
				if ts, ok := n.(*ast.TypeSpec); ok {
					if st, ok := ts.Type.(*ast.StructType); ok {
						structs[ts.Name.Name] = st
					}
				}
				return true
			})
		}
	}

	var buf bytes.Buffer
	buf.WriteString("// Code generated by internal/schema/gen; DO NOT EDIT.\n\npackage model\n\n")
	for _, name := range models {
		st, ok := structs[name]
		if !ok {
			fail(fmt.Errorf("struct %s not found", name))
		}
		leaves := collect(structs, st, "", "")
		if len(leaves) > 64*2 {
			fail(fmt.Errorf("%s has %d fields, exceeds Fields capacity", name, len(leaves)))
		}
		writeModel(&buf, name, leaves)
	}
	src, err := format.Source(buf.Bytes())
	if err != nil {
		fail(fmt.Errorf("format: %w\n%s", err, buf.String()))
	}
	if err := os.WriteFile("fields_gen.go", src, 0o644); err != nil {
		fail(err)
	}
}

func collect(structs map[string]*ast.StructType, st *ast.StructType, identPrefix, wirePrefix string) []leaf {
	var out []leaf
	for _, f := range st.Fields.List {
		if f.Tag == nil || len(f.Names) != 1 {
			continue
		}
		tagText, _ := strconv.Unquote(f.Tag.Value)
		wire := reflect.StructTag(tagText).Get("tq")
		if wire == "" || wire == "-" {
			continue
		}
		ident := identPrefix + f.Names[0].Name
		full := wirePrefix + wire
		if id, ok := f.Type.(*ast.Ident); ok {
			if nested, ok := structs[id.Name]; ok {
				out = append(out, collect(structs, nested, ident, full+".")...)
				continue
			}
		}
		out = append(out, leaf{ident: ident, wire: full})
	}
	return out
}

func writeModel(buf *bytes.Buffer, name string, leaves []leaf) {
	typ := name + "Field"
	lower := strings.ToLower(name[:1]) + name[1:]
	fmt.Fprintf(buf, "// %s 是 %s 的字段编号。\ntype %s uint16\n\n", typ, name, typ)
	fmt.Fprintf(buf, "// %s 字段编号，注释为线上名称。\nconst (\n", name)
	for i, l := range leaves {
		if i == 0 {
			fmt.Fprintf(buf, "\t%s%s %s = iota // %s\n", name, l.ident, typ, l.wire)
		} else {
			fmt.Fprintf(buf, "\t%s%s // %s\n", name, l.ident, l.wire)
		}
	}
	fmt.Fprintf(buf, ")\n\n// %sCount 是 %s 的字段数。\nconst %sCount = %d\n\n", typ, name, typ, len(leaves))
	fmt.Fprintf(buf, "// %sFields 是 %s 的字段集合。\ntype %sFields = Fields[%s]\n\n", name, name, name, typ)
	fmt.Fprintf(buf, "var %sFieldNames = [...]string{\n", lower)
	for _, l := range leaves {
		fmt.Fprintf(buf, "\t%q,\n", l.wire)
	}
	buf.WriteString("}\n\n")
	sorted := append([]leaf(nil), leaves...)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i].wire < sorted[j].wire })
	fmt.Fprintf(buf, "var %sFieldIndex = map[string]%s{\n", lower, typ)
	for _, l := range sorted {
		fmt.Fprintf(buf, "\t%q: %s%s,\n", l.wire, name, l.ident)
	}
	buf.WriteString("}\n\n")
	fmt.Fprintf(buf, `// String 返回字段的线上名称。
func (f %[1]s) String() string {
	if int(f) < len(%[2]sFieldNames) {
		return %[2]sFieldNames[f]
	}
	return "%[1]s(" + itoa(int(f)) + ")"
}

// %[3]sFieldByName 按线上名称（如 "last_price"）查找字段编号。
func %[3]sFieldByName(name string) (%[1]s, bool) {
	f, ok := %[2]sFieldIndex[name]
	return f, ok
}

// All%[3]sFields 返回 %[3]s 的全部字段。
func All%[3]sFields() %[3]sFields { return AllFields[%[1]s](%[1]sCount) }

`, typ, lower, name)
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "schema gen:", err)
	os.Exit(1)
}
